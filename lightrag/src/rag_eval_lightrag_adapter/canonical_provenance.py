"""Deterministic canonical-object to LightRAG runtime-chunk provenance.

The bridge aligns canonicalizer-v1 records to their exact execution-Markdown
rendering, then intersects those source intervals with LightRAG's persisted
runtime chunk intervals. It never reads Gold and never searches with an answer.
Ambiguous, missing, malformed, or content-mismatched provenance fails closed.
"""

from __future__ import annotations

import hashlib
import json
import re
import unicodedata
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping

from rag_eval.datasets.canonical_segments import CanonicalSegmentManifest

MAP_SCHEMA_VERSION = 2
CANONICAL_SEGMENT_MAPPING_MODE = "canonical_segment"
SUPPORTED_CANONICALIZER = "rag-eval-authoring-canonicalizer/1"
SUPPORTED_NATIVE_DOCX_CANONICALIZER = "rag-eval-authoring-canonicalizer/2"
# The platform's current OOXML canonicalizer keeps the same structural
# coordinates as the native /2 contract while publishing the contract as /5.
# Accept both identities here; the source SHA and locator checks below remain
# mandatory for either version.
SUPPORTED_NATIVE_DOCX_CANONICALIZERS = frozenset(
    {SUPPORTED_NATIVE_DOCX_CANONICALIZER, "rag-eval-authoring-canonicalizer/5"}
)
NATIVE_WITNESS_SCHEMA = "nfkc-whitespace-v1"


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_text(value: str) -> str:
    return sha256_bytes(value.encode("utf-8"))


def _is_sha256(value: Any) -> bool:
    return isinstance(value, str) and len(value) == 64 and all(
        character in "0123456789abcdef" for character in value
    )


def _native_witness_text(value: Any) -> str | None:
    """Serialize a parser/canonical witness without using it for lookup."""

    if value is None:
        return None
    if isinstance(value, str):
        return value
    try:
        return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    except (TypeError, ValueError):
        return str(value)


def _native_normalized_witness(value: Any) -> str | None:
    text = _native_witness_text(value)
    if text is None:
        return None
    return " ".join(unicodedata.normalize("NFKC", text).split())


def _native_witness_sha256(value: Any) -> str | None:
    """Hash the canonical witness in the shared native value domain.

    Native parser lineage records use the conservative witness domain (NFKC
    followed by whitespace collapsing).  The run catalog and every forward /
    reverse edge must use that same domain; hashing the raw JSON/string value
    in one place and the normalized value in another makes an otherwise
    correct catalog fail its independent round-trip check (notably for full-
    width punctuation in Chinese text).
    """

    normalized = _native_normalized_witness(value)
    return sha256_text(normalized) if normalized is not None else None


_NATIVE_GENERATED_NUMBERING = re.compile(
    r"^\s*\d+(?:\.\d+)*(?:[.)])?\s+"
)


def _native_paragraph_witness_matches(
    parser_text: str, canonical_text: str
) -> bool:
    """Allow only the parser's deterministic automatic-number prefix.

    The native parser includes Word's computed list label in a paragraph
    atom, while the canonical DOCX catalog stores the authored paragraph
    value.  The prefix is not a text lookup: it is a bounded rendering
    transform, and the structural locator plus the parsed span still have to
    identify the same paragraph.  Any other text difference remains a hard
    witness failure.
    """

    if parser_text == canonical_text:
        return True
    if _native_normalized_witness(parser_text) == _native_normalized_witness(
        canonical_text
    ):
        return True
    match = _NATIVE_GENERATED_NUMBERING.match(parser_text)
    return bool(
        match
        and _native_normalized_witness(parser_text[match.end() :])
        == _native_normalized_witness(canonical_text)
    )


def _native_witness_matches(
    source: dict[str, Any],
    item: NativeDocxCanonicalObject,
    *,
    content: str | None = None,
    document: NativeDocxDocumentMap | None = None,
) -> bool:
    """Require parser and canonical witnesses to agree for one edge.

    Structural coordinates choose the candidate.  These values are only
    witnesses after that choice: a changed cell/paragraph cannot inherit an
    object's identity merely because its coordinates happen to line up.
    """

    parser_value = source.get("source_value")
    canonical_value = item.canonical_value
    parser_text = _native_witness_text(parser_value)
    canonical_text = _native_witness_text(canonical_value)
    if parser_text is None or canonical_text is None:
        return False
    # Paragraph numbering is generated by the native renderer and is absent
    # from canonical authored values.  Cell and table witnesses must remain
    # exact (apart from the hash's historical whitespace normalization).
    if item.object_type in {"paragraph", "block", "heading", "text_span"}:
        if not _native_paragraph_witness_matches(parser_text, canonical_text):
            return False
    elif item.object_type in {"cell", "table_cell", "logical_cell"}:
        if _native_normalized_witness(parser_value) != _native_normalized_witness(
            canonical_value
        ):
            # python-docx exposes the origin text again for a vertical-merge
            # continuation, whereas the canonical physical cell is empty.
            # This is a known representation transform, but it is accepted
            # only when the continuation points to a catalogued origin and
            # the parser witness equals that origin exactly.
            if not (
                canonical_text == ""
                and item.locator.get("v_merge") == "continue"
                and document is not None
                and isinstance(
                    item.raw_record.get("merged_cell_origin_physical_id"), str
                )
                and any(
                    origin.object_id
                    == item.raw_record.get("merged_cell_origin_physical_id")
                    and origin.canonical_value == parser_text
                    for origin in document.objects
                )
            ):
                return False
    elif _native_normalized_witness(parser_value) != _native_normalized_witness(
        canonical_value
    ):
        return False

    # When the parser supplied a valid rendered span, validate the actual
    # serialized witness as well.  Invalid/out-of-bounds spans are deliberately
    # left for _native_runtime_edge, which records a partial edge and never
    # clamps it into a full mapping.
    span = normalize_source_span(source.get("parsed_span"))
    span_valid = (
        content is not None
        and span is not None
        and 0 <= span[0] < span[1] <= len(content)
    )
    if (
        span_valid
        and content is not None
        and str(source.get("coverage_status") or "complete") == "complete"
        and item.object_type in {
        "paragraph",
        "block",
        "heading",
        "text_span",
        }
    ):
        if content[span[0] : span[1]] != parser_text:
            return False
    elif (
        span_valid
        and content is not None
        and str(source.get("coverage_status") or "complete") == "complete"
        and item.object_type in {
        "cell",
        "table_cell",
        "logical_cell",
        }
    ):
        try:
            parsed_value = json.loads(content[span[0] : span[1]])
        except (TypeError, ValueError, json.JSONDecodeError):
            return False
        if _native_witness_text(parsed_value) != parser_text:
            return False
    reported_hash = source.get("source_value_sha256")
    if isinstance(reported_hash, str) and reported_hash:
        # The native parser contract publishes this hash in the same
        # normalized domain as the catalog.  Do not accept a raw-value hash
        # here: forwarding it would make a full-width punctuation/newline
        # variant look like a different witness in the run-level map.
        expected_parser_hash = _native_witness_sha256(parser_value)
        if reported_hash != expected_parser_hash:
            return False
    if item.witness_sha256:
        expected_canonical_hash = _native_witness_sha256(canonical_value)
        if item.witness_sha256 != expected_canonical_hash:
            return False
    return True


@dataclass(frozen=True, slots=True)
class CanonicalObjectSpan:
    object_id: str
    object_type: str
    status: str
    start: int
    end: int
    locator: dict[str, Any]
    witness_sha256: str
    alignment_method: str
    structure: dict[str, Any]

    def as_dict(self) -> dict[str, Any]:
        return {
            "object_id": self.object_id,
            "object_type": self.object_type,
            "status": self.status,
            "source_span": {"start": self.start, "end": self.end},
            "locator": self.locator,
            "witness_sha256": self.witness_sha256,
            "alignment_method": self.alignment_method,
            "structure": self.structure,
        }


@dataclass(frozen=True, slots=True)
class CanonicalDocumentMap:
    document_id: str
    source_sha256: str
    canonical_sidecar_sha256: str
    canonical_digest: str | None
    canonicalizer: str | None
    objects: tuple[CanonicalObjectSpan, ...]
    sections: tuple[dict[str, Any], ...]
    diagnostics: tuple[dict[str, str], ...]

    def intersect(self, start: int, end: int) -> list[dict[str, Any]]:
        mappings: list[dict[str, Any]] = []
        for item in self.objects:
            overlap_start = max(start, item.start)
            overlap_end = min(end, item.end)
            if overlap_start >= overlap_end:
                continue
            coverage = "full" if start <= item.start and end >= item.end else "partial"
            mappings.append(
                {
                    **item.as_dict(),
                    "overlap_span": {
                        "start": overlap_start,
                        "end": overlap_end,
                    },
                    "coverage": coverage,
                }
            )
        return mappings

    def as_dict(self) -> dict[str, Any]:
        return {
            "document_id": self.document_id,
            "source_sha256": self.source_sha256,
            "canonical_sidecar_sha256": self.canonical_sidecar_sha256,
            "canonical_digest": self.canonical_digest,
            "canonicalizer": self.canonicalizer,
            "objects": [item.as_dict() for item in self.objects],
            "sections": list(self.sections),
            "diagnostics": list(self.diagnostics),
        }

    def structure_for_span(
        self, start: int, end: int, mappings: list[dict[str, Any]]
    ) -> dict[str, Any]:
        """Project canonical-only structure onto one verified runtime chunk.

        Section assignment is derived from the execution source intervals of
        canonical headings.  A chunk crossing a heading boundary is marked
        partial rather than silently attributed to an arbitrary section.
        """

        overlaps: list[tuple[int, dict[str, Any]]] = []
        for section in self.sections:
            interval = section.get("active_source_span")
            if not isinstance(interval, dict):
                continue
            section_start = interval.get("start")
            section_end = interval.get("end")
            if not isinstance(section_start, int) or not isinstance(section_end, int):
                continue
            overlap = min(end, section_end) - max(start, section_start)
            if overlap > 0:
                overlaps.append((overlap, section))
        if not overlaps:
            return {
                "metadata_status": "missing",
                "missing_fields": ["section_mapping"],
                "section_ids": [],
                "canonical_object_count": len(mappings),
            }

        overlaps.sort(
            key=lambda item: (
                -item[0],
                int(item[1].get("document_order") or -1),
                str(item[1].get("section_id") or ""),
            )
        )
        primary = overlaps[0][1]
        section_ids = [str(section.get("section_id")) for _, section in overlaps]
        object_structures = [
            item.get("structure")
            for item in mappings
            if isinstance(item, dict) and isinstance(item.get("structure"), dict)
        ]
        object_types = sorted(
            {
                str(item.get("object_type"))
                for item in mappings
                if isinstance(item, dict) and item.get("object_type")
            }
        )
        orders = [
            value.get("document_order")
            for value in object_structures
            if isinstance(value.get("document_order"), int)
        ]
        statuses = {
            str(value.get("metadata_status"))
            for value in object_structures
            if value.get("metadata_status")
        }
        status = "complete"
        missing_fields: list[str] = []
        if len(overlaps) != 1 or statuses - {"complete"}:
            status = "partial"
        if len(overlaps) != 1:
            missing_fields.append("single_section_mapping")
        if not object_structures:
            status = "partial"
            missing_fields.append("canonical_object_structure")
        if statuses - {"complete"}:
            missing_fields.append("complete_canonical_object_structure")
        return {
            "metadata_status": status,
            "missing_fields": missing_fields,
            "section_id": primary.get("section_id"),
            "heading_path": primary.get("heading_path"),
            "parent_section_id": primary.get("parent_section_id"),
            "section_role": primary.get("section_role"),
            "document_order": min(orders) if orders else None,
            "document_order_range": (
                {"start": min(orders), "end": max(orders)} if orders else None
            ),
            "section_ids": section_ids,
            "section_overlap_chars": {
                str(section.get("section_id")): overlap for overlap, section in overlaps
            },
            "canonical_object_count": len(mappings),
            "canonical_object_types": object_types,
            "table_ids": sorted(
                {
                    str(value.get("table_id"))
                    for value in object_structures
                    if value.get("table_id")
                }
            ),
            "row_ids": sorted(
                {
                    str(value.get("row_id"))
                    for value in object_structures
                    if value.get("row_id")
                }
            ),
        }


@dataclass(frozen=True, slots=True)
class NativeDocxCanonicalTable:
    """One canonicalizer-v2 physical table, keyed by its exact cell grid.

    LightRAG parses an uploaded DOCX itself, so it does not expose the authored
    text stream used by the v1 interval bridge. Its table trace does preserve a
    JSON cell grid, though. We map a runtime table only when the *entire*
    normalized grid has one, and only one, canonical counterpart. The mapping
    stays deterministic, document-scoped, and independent of Gold.
    """

    table_id: str
    grid: tuple[tuple[str, ...], ...]
    cells: tuple[dict[str, Any], ...]


@dataclass(frozen=True, slots=True)
class NativeDocxCanonicalObject:
    """One source object retained in the native DOCX catalog.

    The adapter never infers an object from its text.  ``locator`` is the
    typed OOXML structural locator emitted by the canonicalizer, while
    ``expected_extent`` carries the table/cell extent needed to audit partial
    row-split coverage.
    """

    object_id: str
    object_type: str
    representation_status: str
    source_sha256: str
    locator: dict[str, Any]
    expected_extent: dict[str, Any]
    canonical_value: str | None
    witness_sha256: str | None
    raw_record: dict[str, Any]

    def as_dict(self) -> dict[str, Any]:
        # ``locator`` is the platform-facing typed locator.  Keep the raw
        # OOXML coordinates separately because the runtime mapper needs them
        # to select candidates, while CorpusEvidenceIndex must be able to
        # compare the catalog and edge locators without guessing a shape.
        return {
            "object_id": self.object_id,
            "object_type": self.object_type,
            "representation_status": self.representation_status,
            "source_sha256": self.source_sha256,
            "locator": _native_typed_locator(self.raw_record, self.locator),
            "source_locator": self.locator,
            "expected_extent": self.expected_extent,
            "canonical_value": self.canonical_value,
            "witness_sha256": self.witness_sha256,
            "witness_schema": NATIVE_WITNESS_SCHEMA,
        }


@dataclass(frozen=True, slots=True)
class NativeDocxDocumentMap:
    document_id: str
    canonical_sidecar_sha256: str
    canonical_digest: str | None
    canonicalizer: str | None
    tables: tuple[NativeDocxCanonicalTable, ...]
    diagnostics: tuple[dict[str, str], ...]
    source_sha256: str = ""
    objects: tuple[NativeDocxCanonicalObject, ...] = ()

    def as_dict(self) -> dict[str, Any]:
        return {
            "document_id": self.document_id,
            "source_sha256": self.source_sha256,
            "canonical_sidecar_sha256": self.canonical_sidecar_sha256,
            "canonical_digest": self.canonical_digest,
            "canonicalizer": self.canonicalizer,
            "native_table_count": len(self.tables),
            "object_catalog": [item.as_dict() for item in self.objects],
            "diagnostics": list(self.diagnostics),
        }


def load_canonical_document_map(
    *,
    document_id: str,
    source: str,
    sidecar_path: Path,
    expected_sidecar_sha256: str,
) -> CanonicalDocumentMap:
    payload = sidecar_path.read_bytes()
    actual_digest = sha256_bytes(payload)
    if actual_digest != expected_sidecar_sha256:
        raise ValueError("canonical provenance sidecar digest mismatch")
    records: list[dict[str, Any]] = []
    for line_number, line in enumerate(payload.decode("utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        value = json.loads(line)
        if not isinstance(value, dict):
            raise ValueError(
                f"canonical provenance line {line_number} is not an object"
            )
        if value.get("document_id") != document_id:
            raise ValueError(
                f"canonical provenance line {line_number} has wrong document_id"
            )
        records.append(value)
    if not records:
        raise ValueError("canonical provenance sidecar is empty")
    canonicalizers = {
        str(record.get("canonicalizer"))
        for record in records
        if record.get("canonicalizer")
    }
    canonicalizer = next(iter(canonicalizers)) if len(canonicalizers) == 1 else None
    canonical_digests = {
        str(record.get("canonical_digest"))
        for record in records
        if record.get("canonical_digest")
    }
    canonical_digest = (
        next(iter(canonical_digests)) if len(canonical_digests) == 1 else None
    )
    if canonicalizer != SUPPORTED_CANONICALIZER:
        return CanonicalDocumentMap(
            document_id=document_id,
            source_sha256=sha256_text(source),
            canonical_sidecar_sha256=actual_digest,
            canonical_digest=canonical_digest,
            canonicalizer=canonicalizer,
            objects=(),
            sections=(),
            diagnostics=(
                {
                    "reason": "unsupported_canonicalizer",
                    "object_id": "",
                },
            ),
        )
    structures, section_specs = _build_canonical_structure(records)
    objects, diagnostics = _align_canonicalizer_v1(source, records, structures)
    return CanonicalDocumentMap(
        document_id=document_id,
        source_sha256=sha256_text(source),
        canonical_sidecar_sha256=actual_digest,
        canonical_digest=canonical_digest,
        canonicalizer=canonicalizer,
        objects=tuple(objects),
        sections=tuple(_materialize_sections(section_specs, objects, source)),
        diagnostics=tuple(diagnostics),
    )


def runtime_chunk_mapping(
    *,
    chunk_id: str,
    document: CanonicalDocumentMap,
    source: str,
    content: str,
    source_span: Any,
) -> dict[str, Any]:
    base: dict[str, Any] = {
        "runtime_chunk_id": chunk_id,
        "document_id": document.document_id,
        "content_sha256": sha256_text(content),
        "provenance_status": "missing",
        "canonical_objects": [],
        "structure": {
            "metadata_status": "missing",
            "missing_fields": ["verified_source_span", "canonical_object_mapping"],
            "section_ids": [],
            "canonical_object_count": 0,
        },
    }
    span = normalize_source_span(source_span)
    if span is None:
        base["reason"] = "missing_or_malformed_source_span"
        return base
    start, end = span
    base["source_span"] = {"start": start, "end": end}
    if end > len(source):
        base["reason"] = "source_span_out_of_bounds"
        return base
    witness = source[start:end]
    base["source_witness_sha256"] = sha256_text(witness)
    if witness != content:
        base["reason"] = "runtime_content_source_witness_mismatch"
        return base
    mappings = document.intersect(start, end)
    base["canonical_objects"] = mappings
    if not mappings:
        base["reason"] = "no_canonical_object_overlap"
        base["structure"] = {
            "metadata_status": "missing",
            "missing_fields": ["canonical_object_mapping"],
            "section_ids": [],
            "canonical_object_count": 0,
        }
        return base
    base["provenance_status"] = (
        "full" if any(item["coverage"] == "full" for item in mappings) else "partial"
    )
    base["structure"] = document.structure_for_span(start, end, mappings)
    return base


def build_provenance_manifest(
    *,
    documents: dict[str, CanonicalDocumentMap],
    sources: dict[str, str],
    document_by_file: dict[str, str],
    stored_chunks: dict[str, dict[str, Any]],
) -> dict[str, Any]:
    runtime_chunks: dict[str, dict[str, Any]] = {}
    object_to_runtime_chunks: dict[str, list[dict[str, Any]]] = {}
    for chunk_id in sorted(stored_chunks):
        record = stored_chunks[chunk_id]
        file_name = Path(str(record.get("file_path") or "")).name
        document_id = document_by_file.get(file_name)
        if document_id is None or document_id not in documents:
            continue
        mapping = runtime_chunk_mapping(
            chunk_id=chunk_id,
            document=documents[document_id],
            source=sources[document_id],
            content=str(record.get("content") or ""),
            source_span=record.get("source_span"),
        )
        token_count = record.get("tokens")
        if isinstance(token_count, int) and not isinstance(token_count, bool):
            mapping["runtime_token_count"] = token_count
        else:
            mapping["runtime_token_count"] = None
        runtime_chunks[chunk_id] = mapping
        for item in mapping["canonical_objects"]:
            object_to_runtime_chunks.setdefault(item["object_id"], []).append(
                {
                    "runtime_chunk_id": chunk_id,
                    "coverage": item["coverage"],
                    "overlap_span": item["overlap_span"],
                }
            )
    for values in object_to_runtime_chunks.values():
        values.sort(key=lambda item: item["runtime_chunk_id"])
    object_catalog = {
        item.object_id: {
            **item.as_dict(),
            "document_id": document_id,
        }
        for document_id, document in documents.items()
        for item in document.objects
    }
    return {
        "schema_version": MAP_SCHEMA_VERSION,
        "documents": {key: documents[key].as_dict() for key in sorted(documents)},
        "runtime_chunks": runtime_chunks,
        "object_to_runtime_chunks": {
            key: object_to_runtime_chunks[key]
            for key in sorted(object_to_runtime_chunks)
        },
        "reverse_index": {
            key: object_to_runtime_chunks[key]
            for key in sorted(object_to_runtime_chunks)
        },
        "object_catalog": object_catalog,
    }


def build_canonical_segment_provenance_manifest(
    *,
    manifest: CanonicalSegmentManifest,
    document_by_file: Mapping[str, str],
    stored_chunks: Mapping[str, Mapping[str, Any]],
) -> dict[str, Any]:
    """Build a strict, non-heuristic chunk-to-segment provenance map.

    A canonical input batch is deliberately small enough to be one LightRAG
    text chunk.  We verify that observed fact rather than assuming a tokenizer
    conversion.  A split/merged/transformed batch is rejected here, before a
    caller can execute a query or call an evidence result a retrieval miss.
    """

    batches_by_input = {item.input_document_id: item for item in manifest.batches}
    batches_by_id = {item.batch_id: item for item in manifest.batches}
    segment_by_id = {item.segment_id: item for item in manifest.segments}
    source_by_document = {item.document_id: item for item in manifest.sources}
    catalog_by_id = {item.object_id: item for item in manifest.object_catalog}

    chunks_by_batch: dict[str, list[tuple[str, Mapping[str, Any]]]] = {
        item.batch_id: [] for item in manifest.batches
    }
    unknown_chunks: list[str] = []
    for chunk_id, record in sorted(stored_chunks.items()):
        if not isinstance(record, Mapping):
            raise ValueError(f"LightRAG stored chunk {chunk_id!r} is malformed")
        file_name = Path(str(record.get("file_path") or "")).name
        input_document_id = document_by_file.get(file_name)
        batch = batches_by_input.get(input_document_id or "")
        if batch is None:
            unknown_chunks.append(str(chunk_id))
            continue
        chunks_by_batch[batch.batch_id].append((str(chunk_id), record))
    if unknown_chunks:
        preview = ", ".join(unknown_chunks[:8])
        suffix = " …" if len(unknown_chunks) > 8 else ""
        raise ValueError(
            "LightRAG persisted chunks outside the canonical input manifest: "
            f"{preview}{suffix}"
        )

    runtime_chunks: dict[str, dict[str, Any]] = {}
    reverse_index: dict[str, list[dict[str, Any]]] = defaultdict(list)
    batch_to_runtime_chunks: dict[str, list[str]] = {}
    runtime_chunk_to_segment_ids: dict[str, list[str]] = {}
    segment_to_runtime_chunks: dict[str, list[str]] = {
        segment_id: [] for segment_id in segment_by_id
    }
    for batch_id, batch in sorted(batches_by_id.items()):
        observed = chunks_by_batch.get(batch_id, [])
        if len(observed) != 1:
            raise ValueError(
                f"canonical batch {batch_id!r} must persist as exactly one LightRAG "
                f"chunk, observed {len(observed)}"
            )
        runtime_chunk_id, record = observed[0]
        content = record.get("content")
        if not isinstance(content, str) or content != batch.content:
            raise ValueError(
                f"LightRAG chunk {runtime_chunk_id!r} does not preserve canonical "
                f"batch {batch_id!r} bytes"
            )
        source_span = normalize_source_span(record.get("source_span"))
        if source_span != (0, len(batch.content)):
            raise ValueError(
                f"LightRAG chunk {runtime_chunk_id!r} does not expose the complete "
                f"canonical batch source span"
            )
        source = source_by_document[batch.document_id]
        edges: list[dict[str, Any]] = []
        for segment_id in batch.segment_ids:
            segment = segment_by_id[segment_id]
            for segment_edge in segment.edges:
                catalog = catalog_by_id.get(segment_edge.object_id)
                if catalog is None:
                    raise ValueError(
                        f"segment {segment_id!r} references an unknown canonical object"
                    )
                if catalog.document_id != batch.document_id:
                    raise ValueError(
                        f"segment {segment_id!r} crosses source document identities"
                    )
                edge = {
                    "runtime_chunk_id": runtime_chunk_id,
                    "object_id": catalog.object_id,
                    "object_type": catalog.object_type,
                    "document_id": catalog.document_id,
                    "locator": catalog.locator,
                    "expected_extent": catalog.expected_extent,
                    "source_sha256": catalog.source_sha256,
                    "witness_sha256": catalog.witness_sha256,
                    "coverage": segment_edge.coverage,
                    "segment_id": segment_id,
                }
                # Omit nulls to retain the strict, simple evidence envelope.
                edge = {key: value for key, value in edge.items() if value is not None}
                edges.append(edge)
                reverse_index[catalog.object_id].append(dict(edge))
        runtime_chunks[runtime_chunk_id] = {
            "runtime_chunk_id": runtime_chunk_id,
            "document_id": batch.document_id,
            "input_document_id": batch.input_document_id,
            "full_doc_id": record.get("full_doc_id"),
            "batch_id": batch_id,
            "segment_ids": list(batch.segment_ids),
            "mapping_mode": CANONICAL_SEGMENT_MAPPING_MODE,
            "canonical_segment_manifest_digest": manifest.manifest_digest,
            "source_sha256": source.source_sha256,
            "canonical_sidecar_sha256": source.canonical_sidecar_sha256,
            "content_sha256": sha256_text(content),
            "source_span": {"start": source_span[0], "end": source_span[1]},
            "source_span_status": "verified",
            "provenance_status": "full",
            "attribution_status": "full",
            "canonical_objects": edges,
        }
        batch_to_runtime_chunks[batch_id] = [runtime_chunk_id]
        runtime_chunk_to_segment_ids[runtime_chunk_id] = list(batch.segment_ids)
        for segment_id in batch.segment_ids:
            segment_to_runtime_chunks[segment_id].append(runtime_chunk_id)

    missing_segments = [
        segment_id
        for segment_id, runtime_ids in segment_to_runtime_chunks.items()
        if len(runtime_ids) != 1
    ]
    if missing_segments:
        preview = ", ".join(missing_segments[:8])
        suffix = " …" if len(missing_segments) > 8 else ""
        raise ValueError(
            "canonical segment(s) lack exactly one persisted runtime chunk: "
            f"{preview}{suffix}"
        )

    object_catalog = {
        item.object_id: item.model_dump(mode="json") for item in manifest.object_catalog
    }
    segment_catalog = {
        item.segment_id: {
            "segment_id": item.segment_id,
            "document_id": item.document_id,
            "root_object_id": item.root_object_id,
            "content_sha256": item.content_sha256,
            "batch_id": next(
                batch.batch_id
                for batch in manifest.batches
                if item.segment_id in batch.segment_ids
            ),
            "canonical_object_ids": [edge.object_id for edge in item.edges],
        }
        for item in manifest.segments
    }
    return {
        "schema_version": MAP_SCHEMA_VERSION,
        "primary_corpus": {
            "mode": "canonical-segments/v1",
            "manifest_digest": manifest.manifest_digest,
            "acceptance": "one_persisted_chunk_per_declared_batch",
        },
        "documents": {
            item.document_id: {
                "document_id": item.document_id,
                "source_sha256": item.source_sha256,
                "canonical_sidecar_sha256": item.canonical_sidecar_sha256,
            }
            for item in manifest.sources
        },
        "segment_catalog": segment_catalog,
        "runtime_chunks": runtime_chunks,
        "runtime_chunk_to_segment_ids": runtime_chunk_to_segment_ids,
        "batch_to_runtime_chunks": batch_to_runtime_chunks,
        "segment_to_runtime_chunks": segment_to_runtime_chunks,
        "object_catalog": object_catalog,
        "object_to_runtime_chunks": {
            object_id: sorted(values, key=lambda value: str(value["runtime_chunk_id"]))
            for object_id, values in sorted(reverse_index.items())
        },
        "reverse_index": {
            object_id: sorted(values, key=lambda value: str(value["runtime_chunk_id"]))
            for object_id, values in sorted(reverse_index.items())
        },
    }


def load_native_docx_document_map(
    *,
    document_id: str,
    sidecar_path: Path,
    expected_sidecar_sha256: str,
) -> NativeDocxDocumentMap:
    """Load the v2 DOCX table graph used for native-parser attribution.

    This intentionally accepts only the stable physical-cell representation.
    Logical cells, table summaries, and partial records cannot prove a runtime
    table's coordinates and are therefore ignored rather than guessed.
    """

    payload = sidecar_path.read_bytes()
    actual_digest = sha256_bytes(payload)
    if actual_digest != expected_sidecar_sha256:
        raise ValueError("canonical provenance sidecar digest mismatch")
    records = _read_canonical_records(document_id, payload)
    canonicalizers = {
        _canonicalizer_identity(record)
        for record in records
        if _canonicalizer_identity(record) is not None
    }
    canonicalizer = next(iter(canonicalizers)) if len(canonicalizers) == 1 else None
    canonical_digests = {
        str(record.get("canonical_digest"))
        for record in records
        if isinstance(record.get("canonical_digest"), str)
    }
    canonical_digest = (
        next(iter(canonical_digests)) if len(canonical_digests) == 1 else None
    )
    if canonicalizer not in SUPPORTED_NATIVE_DOCX_CANONICALIZERS:
        return NativeDocxDocumentMap(
            document_id=document_id,
            canonical_sidecar_sha256=actual_digest,
            canonical_digest=canonical_digest,
            canonicalizer=canonicalizer,
            tables=(),
            diagnostics=(({"reason": "unsupported_canonicalizer", "object_id": ""}),),
        )

    source_shas = {
        _native_source_sha256(record)
        for record in records
        if _native_source_sha256(record)
    }
    source_sha256 = (
        next(iter(source_shas))
        if len(source_shas) == 1 and _is_sha256(next(iter(source_shas)))
        else ""
    )
    table_cells: dict[str, dict[tuple[int, int], dict[str, Any]]] = {}
    diagnostics: list[dict[str, str]] = []
    if len(source_shas) > 1:
        diagnostics.append(
            {"reason": "mixed_native_source_sha256", "object_id": ""}
        )
    for source_sha in sorted(source_shas):
        if not _is_sha256(source_sha):
            diagnostics.append(
                {
                    "reason": "malformed_native_source_sha256",
                    "object_id": "",
                }
            )
    objects: list[NativeDocxCanonicalObject] = []
    for record in records:
        object_type = _native_object_type(record)
        object_id = record.get("object_id")
        record_sha = _native_source_sha256(record)
        locator = _native_structural_locator(record)
        if not isinstance(object_id, str) or not object_id:
            diagnostics.append(
                {
                    "reason": "malformed_native_object_id",
                    "object_id": str(object_id or ""),
                }
            )
            continue
        if source_sha256 and record_sha and record_sha != source_sha256:
            diagnostics.append(
                {"reason": "mixed_native_source_sha256", "object_id": object_id}
            )
            continue
        if not record_sha:
            diagnostics.append(
                {
                    "reason": "native_object_source_sha256_missing",
                    "object_id": object_id,
                }
            )
        canonical_value = record.get("canonical_value")
        objects.append(
            NativeDocxCanonicalObject(
                object_id=object_id,
                object_type=object_type,
                representation_status=_native_status(record),
                source_sha256=record_sha,
                locator=locator,
                expected_extent=_native_object_expected_extent(record, locator),
                canonical_value=(
                    str(canonical_value) if canonical_value is not None else None
                ),
                witness_sha256=(
                    _native_witness_sha256(canonical_value)
                    if canonical_value is not None
                    else None
                ),
                raw_record=dict(record),
            )
        )
        if object_type not in {"cell", "table_cell"}:
            continue
        table_id = record.get("table_id")
        if not isinstance(table_id, str) or not table_id:
            table_id = locator.get("table_id")
        row = record.get("row")
        if row is None:
            row = locator.get("row")
        column = record.get("column")
        if column is None:
            column = locator.get("column")
        if (
            not isinstance(table_id, str)
            or not table_id
            or not isinstance(row, int)
            or isinstance(row, bool)
            or row < 1
            or not isinstance(column, int)
            or isinstance(column, bool)
            or column < 1
            or not isinstance(object_id, str)
            or not object_id
        ):
            diagnostics.append(
                {
                    "reason": "malformed_physical_table_cell",
                    "object_id": str(object_id or ""),
                }
            )
            continue
        position = (row, column)
        cells = table_cells.setdefault(table_id, {})
        if position in cells:
            diagnostics.append(
                {"reason": "duplicate_physical_table_cell", "object_id": object_id}
            )
            continue
        cells[position] = record

    tables: list[NativeDocxCanonicalTable] = []
    for table_id, cells_by_position in sorted(table_cells.items()):
        max_row = max(row for row, _ in cells_by_position)
        max_column = max(column for _, column in cells_by_position)
        expected_positions = {
            (row, column)
            for row in range(1, max_row + 1)
            for column in range(1, max_column + 1)
        }
        if set(cells_by_position) != expected_positions:
            diagnostics.append(
                {"reason": "incomplete_physical_table_grid", "object_id": table_id}
            )
            continue
        grid = tuple(
            tuple(
                _normalize_table_cell(cells_by_position[(row, column)].get("canonical_value"))
                for column in range(1, max_column + 1)
            )
            for row in range(1, max_row + 1)
        )
        cell_mappings = tuple(
            {
                "object_id": str(cells_by_position[(row, column)]["object_id"]),
                "object_type": "cell",
                "status": str(
                    cells_by_position[(row, column)].get("representation_status")
                    or "complete"
                ),
                "locator": {
                    "type": "table_cell",
                    "table_id": table_id,
                    "row": row,
                    "column": column,
                },
                "alignment_method": "canonicalizer_v2_native_docx_exact_table_grid",
                "structure": {
                    "metadata_status": "partial",
                    "missing_fields": ["section_mapping", "execution_text_span"],
                    "table_id": table_id,
                    "table_row_index": row,
                    "table_column_index": column,
                    "object_role": "table_cell",
                },
            }
            for row in range(1, max_row + 1)
            for column in range(1, max_column + 1)
        )
        tables.append(
            NativeDocxCanonicalTable(
                table_id=table_id,
                grid=grid,
                cells=cell_mappings,
            )
        )
    return NativeDocxDocumentMap(
        document_id=document_id,
        canonical_sidecar_sha256=actual_digest,
        canonical_digest=canonical_digest,
        canonicalizer=canonicalizer,
        tables=tuple(tables),
        diagnostics=tuple(sorted(diagnostics, key=lambda item: (item["object_id"], item["reason"]))),
        source_sha256=source_sha256,
        objects=tuple(sorted(objects, key=lambda item: item.object_id)),
    )


def build_native_docx_provenance_manifest(
    *,
    documents: dict[str, NativeDocxDocumentMap],
    document_by_file: dict[str, str],
    stored_chunks: dict[str, dict[str, Any]],
    allow_historical_fallback: bool = False,
) -> dict[str, Any]:
    runtime_chunks: dict[str, dict[str, Any]] = {}
    object_to_runtime_chunks: dict[str, list[dict[str, Any]]] = {}
    for chunk_id in sorted(stored_chunks):
        record = stored_chunks[chunk_id]
        file_name = Path(str(record.get("file_path") or "")).name
        document_id = document_by_file.get(file_name)
        if document_id is None or document_id not in documents:
            continue
        mapping = native_docx_runtime_chunk_mapping(
            chunk_id=chunk_id,
            document=documents[document_id],
            content=str(record.get("content") or ""),
            source_span=record.get("source_span"),
            lineage=record.get("lineage"),
            source_sha256=documents[document_id].source_sha256,
            allow_historical_fallback=allow_historical_fallback,
        )
        runtime_document_id = record.get("full_doc_id")
        if isinstance(runtime_document_id, str) and runtime_document_id:
            mapping["native_document_id"] = runtime_document_id
        token_count = record.get("tokens")
        mapping["runtime_token_count"] = (
            token_count
            if isinstance(token_count, int) and not isinstance(token_count, bool)
            else None
        )
        runtime_chunks[chunk_id] = mapping
        for item in mapping["canonical_objects"]:
            # The reverse index is the run-level object catalog's auditable
            # counterpart.  Keep the same identity-bearing fields as the
            # forward edge so CorpusEvidenceIndex can verify a true miss by
            # round-tripping object id/type, source pin, typed locator,
            # expected extent, witness and covered range.  It is still one
            # sparse edge per runtime chunk, not one evidence item per
            # canonical object.
            reverse_edge = {
                "runtime_chunk_id": chunk_id,
                "document_id": mapping.get("document_id"),
                "object_id": item.get("object_id"),
                "object_type": item.get("object_type"),
                "source_sha256": item.get("source_sha256"),
                "witness_sha256": item.get("witness_sha256"),
                "source_witness_sha256": item.get("source_witness_sha256"),
                "witness_schema": item.get("witness_schema") or NATIVE_WITNESS_SCHEMA,
                "locator": item.get("locator"),
                "source_locator": item.get("source_locator"),
                "expected_extent": item.get("expected_extent"),
                "covered_ranges": item.get("covered_ranges"),
                "coverage": item.get("coverage"),
                "overlap_span": item.get("overlap_span"),
                "mapping_status": item.get("mapping_status")
                or ("complete" if item.get("coverage") == "full" else "partial"),
                "representation_status": item.get("representation_status"),
                "reason": item.get("reason"),
            }
            object_to_runtime_chunks.setdefault(item["object_id"], []).append(
                reverse_edge
            )
    for values in object_to_runtime_chunks.values():
        values.sort(key=lambda item: item["runtime_chunk_id"])
    document_payloads: dict[str, dict[str, Any]] = {}
    for document_id, document in sorted(documents.items()):
        payload = document.as_dict()
        native_document_ids = sorted(
            {
                str(record.get("full_doc_id"))
                for record in stored_chunks.values()
                if isinstance(record, dict)
                and document_by_file.get(
                    Path(str(record.get("file_path") or "")).name
                )
                == document_id
                and isinstance(record.get("full_doc_id"), str)
                and record.get("full_doc_id")
            }
        )
        reverse: dict[str, list[dict[str, Any]]] = {}
        for object_id, values in sorted(object_to_runtime_chunks.items()):
            filtered = [
                dict(value)
                for value in values
                if isinstance(value, dict)
                and isinstance(value.get("runtime_chunk_id"), str)
                and runtime_chunks.get(value["runtime_chunk_id"], {}).get(
                    "document_id"
                )
                == document_id
            ]
            if filtered:
                reverse[object_id] = filtered
        catalog: dict[str, dict[str, Any]] = {}
        for obj in document.objects:
            links = reverse.get(obj.object_id, [])
            statuses = {str(link.get("mapping_status") or "partial") for link in links}
            if not links:
                mapping_status = "unmapped"
                reason = "no_runtime_chunk_mapping"
            elif "partial" in statuses or obj.representation_status != "complete":
                mapping_status = "partial"
                reason = (
                    "canonical_object_partial"
                    if obj.representation_status != "complete"
                    else "runtime_chunk_partial_coverage"
                )
            else:
                # ``complete`` is deliberately distinct from the historical
                # ``mapped`` label: the evaluator accepts only an explicit
                # complete/verified mapping together with an explicit
                # complete expected extent as proof for a true miss.
                mapping_status = "complete"
                reason = None
            catalog[obj.object_id] = {
                **obj.as_dict(),
                "document_id": document_id,
                "mapping_status": mapping_status,
                "mapping_reason": reason,
                "runtime_chunk_ids": [
                    str(link.get("runtime_chunk_id")) for link in links
                ],
            }
        payload["object_catalog"] = catalog
        payload["reverse_index"] = reverse
        payload["native_document_id"] = (
            native_document_ids[0] if len(native_document_ids) == 1 else None
        )
        payload["native_document_ids"] = native_document_ids
        payload["source_coordinate_system"] = "ooxml-structural-v1"
        payload["execution_coordinate_system"] = "lightrag-rendered-stream-v1"
        document_payloads[document_id] = payload
    object_catalog = {
        object_id: entry
        for payload in document_payloads.values()
        for object_id, entry in dict(payload.get("object_catalog") or {}).items()
    }
    native_documents = {
        document_id: {
            "document_id": document_id,
            "native_document_id": payload.get("native_document_id"),
            "source_sha256": payload.get("source_sha256"),
            "canonical_sidecar_sha256": payload.get("canonical_sidecar_sha256"),
            "canonical_digest": payload.get("canonical_digest"),
            "source_coordinate_system": payload.get("source_coordinate_system"),
            "execution_coordinate_system": payload.get("execution_coordinate_system"),
        }
        for document_id, payload in document_payloads.items()
    }
    return {
        "schema_version": MAP_SCHEMA_VERSION,
        "map_kind": "native-docx-runtime-provenance",
        "documents": document_payloads,
        "runtime_chunks": runtime_chunks,
        "object_to_runtime_chunks": {
            key: object_to_runtime_chunks[key] for key in sorted(object_to_runtime_chunks)
        },
        "reverse_index": {
            key: object_to_runtime_chunks[key]
            for key in sorted(object_to_runtime_chunks)
        },
        "object_catalog": object_catalog,
        "native_documents": native_documents,
        "document_source_pins": {
            document_id: {
                "source_sha256": payload.get("source_sha256"),
                "canonical_sidecar_sha256": payload.get("canonical_sidecar_sha256"),
            }
            for document_id, payload in document_payloads.items()
        },
    }


def _native_locator_coordinates(value: dict[str, Any]) -> dict[str, Any]:
    locator = value.get("source_locator")
    return dict(locator) if isinstance(locator, dict) else {}


def _native_coordinate_matches(
    atom_locator: dict[str, Any], object_locator: dict[str, Any]
) -> bool:
    """Compare only explicit OOXML coordinates; never compare rendered text."""

    if not atom_locator or not object_locator:
        return False
    if atom_locator.get("part") and object_locator.get("part") != atom_locator.get("part"):
        return False
    for key in ("body_ordinal", "nested"):
        if key in atom_locator and key in object_locator:
            if object_locator[key] != atom_locator[key]:
                return False
    if "nested_path" in atom_locator and "nested_path" in object_locator:
        if object_locator["nested_path"] != atom_locator["nested_path"]:
            return False
    if "body_ordinal" not in atom_locator or "body_ordinal" not in object_locator:
        return False
    return True


def _native_kind_matches(atom_kind: str, object_item: NativeDocxCanonicalObject) -> bool:
    raw_kind = object_item.object_type
    if atom_kind == "paragraph":
        return raw_kind in {"paragraph", "block", "heading", "text_span"}
    if atom_kind == "table":
        return raw_kind == "table"
    if atom_kind == "table_cell":
        return raw_kind in {"cell", "table_cell", "logical_cell"}
    return raw_kind == atom_kind


def _native_candidates_for_atom(
    atom: dict[str, Any], document: NativeDocxDocumentMap
) -> list[NativeDocxCanonicalObject]:
    atom_kind = str(atom.get("kind") or "")
    atom_locator = _native_locator_coordinates(atom)
    candidates = [
        item
        for item in document.objects
        if _native_kind_matches(atom_kind, item)
        and item.source_sha256 == document.source_sha256
        and _native_coordinate_matches(atom_locator, item.locator)
    ]
    # Prefer the physical cell record when both physical and logical records
    # describe the same grid coordinate. Logical records remain in the catalog
    # but do not create duplicate runtime edges.
    if atom_kind == "table_cell":
        physical = [item for item in candidates if item.object_type in {"cell", "table_cell"}]
        if physical:
            candidates = physical
    elif atom_kind == "paragraph":
        # The canonical sidecar also contains a text_span derived from each
        # block.  Gold's paragraph object is the authored block, so prefer
        # that explicit object kind; if a producer omits blocks, retain the
        # narrower paragraph/heading fallback.  Never merge block and span
        # records into multiple runtime edges.
        authored = [
            item
            for item in candidates
            if item.object_type in {"paragraph", "block", "heading"}
        ]
        if authored:
            candidates = authored
    para_id = atom_locator.get("para_id")
    if para_id is not None:
        exact = [item for item in candidates if item.locator.get("para_id") == para_id]
        if exact:
            candidates = exact
    return candidates


def _native_cell_candidates(
    cell: dict[str, Any],
    *,
    table_atom: dict[str, Any],
    document: NativeDocxDocumentMap,
) -> list[NativeDocxCanonicalObject]:
    locator = cell.get("source_locator")
    if not isinstance(locator, dict):
        return []
    table_locator = table_atom.get("source_locator")
    if not isinstance(table_locator, dict):
        return []
    merged_locator = {
        **table_locator,
        "row": locator.get("row"),
        "column": locator.get("column"),
    }
    candidates = [
        item
        for item in document.objects
        if item.object_type in {"cell", "table_cell", "logical_cell"}
        and item.source_sha256 == document.source_sha256
        and _native_coordinate_matches(merged_locator, item.locator)
        and item.locator.get("row") == locator.get("row")
        and item.locator.get("column") == locator.get("column")
    ]
    physical = [item for item in candidates if item.object_type in {"cell", "table_cell"}]
    return physical or candidates


def _native_runtime_edge(
    item: NativeDocxCanonicalObject,
    *,
    atom: dict[str, Any],
    cell: dict[str, Any] | None,
    content_length: int,
) -> dict[str, Any]:
    source = cell if cell is not None else atom
    raw_parsed_span = source.get("parsed_span")
    parsed_span = normalize_source_span(raw_parsed_span)
    covered_ranges = source.get("covered_ranges")
    if not isinstance(covered_ranges, dict):
        covered_ranges = {}
    else:
        covered_ranges = dict(covered_ranges)
    # ``normalize_source_span`` rejects negative starts before the range can
    # be inspected.  Check the raw producer value as well so an invalid
    # negative/end-overflow span gets a diagnostic and can never be mistaken
    # for an absent-but-complete witness.
    span_out_of_bounds = bool(
        isinstance(raw_parsed_span, dict)
        and isinstance(raw_parsed_span.get("start"), int)
        and not isinstance(raw_parsed_span.get("start"), bool)
        and isinstance(raw_parsed_span.get("end"), int)
        and not isinstance(raw_parsed_span.get("end"), bool)
        and (
            raw_parsed_span["start"] < 0
            or raw_parsed_span["end"] > content_length
        )
    )
    if span_out_of_bounds:
        parsed_span = None
    if parsed_span is not None:
        covered_ranges.setdefault("parsed", {"start": parsed_span[0], "end": parsed_span[1]})
    atom_status = str(atom.get("coverage_status") or "complete")
    source_status = str(source.get("coverage_status") or atom_status)
    # A table envelope may be partial while a physical cell has an exact
    # serialization witness.  The cell owns its completeness; do not let the
    # parent table status downgrade a verified cell.  Conversely, the table
    # edge itself requires the table atom's status.
    full = (
        source_status == "complete"
        and parsed_span is not None
        and item.representation_status == "complete"
        and (cell is not None or atom_status == "complete")
    )
    coverage = "full" if full else "partial"
    # A witness hash is a proof-bearing claim, not a copy of whatever value a
    # renderer happened to expose.  Partial/unsupported objects (including
    # empty merge continuations and drawing carriers) remain diagnosable via
    # the edge's reason/coverage, but must not publish a runtime witness that
    # disagrees with the canonical value.  Only a fully verified serialized
    # span gets the normalized witness digest.
    canonical_witness_sha256 = item.witness_sha256 if full else None
    source_witness_sha256 = (
        _native_witness_sha256(source.get("source_value")) if full else None
    )
    edge: dict[str, Any] = {
        "object_id": item.object_id,
        "object_type": item.object_type,
        "source_sha256": item.source_sha256,
        "locator": _native_typed_locator(item.raw_record, item.locator),
        "source_locator": dict(item.locator),
        "expected_extent": dict(item.expected_extent),
        "covered_ranges": covered_ranges,
        "coverage": coverage,
        # ``complete`` is a proof-bearing status.  ``mapped`` was the old
        # diagnostic spelling and is intentionally not emitted by the formal
        # native bridge because the evaluator reserves complete/verified for
        # a true-miss-capable extent.
        "mapping_status": "complete" if coverage == "full" else "partial",
        # Recompute from the retained raw parser witness in the shared
        # normalized domain.  A producer-supplied hash is checked by
        # _native_witness_matches; copying it directly would let legacy raw
        # hashes poison the catalog round-trip.
        # ``witness_sha256`` is the canonical identity witness.  A parser may
        # apply a documented rendering transform (for example Word's
        # automatic list numbering), so its observed value is retained under
        # a separate diagnostic field and must never replace the canonical
        # hash used by the catalog/reverse round-trip.
        "witness_sha256": canonical_witness_sha256,
        "source_witness_sha256": source_witness_sha256,
        "witness_schema": NATIVE_WITNESS_SCHEMA,
        "canonical_value": item.canonical_value,
        "representation_status": item.representation_status,
    }
    if parsed_span is not None:
        # ``parsed_span`` was bounds-checked above.  Do not clamp an invalid
        # interval into a seemingly valid full witness: clamping hides a
        # producer bug and lets an out-of-bounds edge look authoritative.
        edge["overlap_span"] = {
            "start": parsed_span[0],
            "end": parsed_span[1],
        }
    else:
        edge["overlap_span"] = None
    if item.representation_status != "complete":
        edge["mapping_status"] = "partial"
        edge["reason"] = "canonical_object_partial"
    elif span_out_of_bounds:
        edge["mapping_status"] = "partial"
        edge["reason"] = "runtime_parsed_span_out_of_bounds"
    elif source_status != "complete":
        edge["reason"] = str(source.get("missing_reason") or "runtime_source_partial")
    elif cell is None and atom_status != "complete":
        edge["reason"] = str(atom.get("missing_reason") or "runtime_atom_partial")
    return edge


def _native_formal_edge(edge: Mapping[str, Any]) -> bool:
    """Return whether an edge is safe for the run-level proof index.

    Partial/unsupported scopes are useful diagnostics on a runtime item, but
    putting them in ``canonical_objects`` would make the platform treat them
    as forward identity projections.  In particular, empty merge
    continuations and renderer-only drawing carriers must not poison a
    complete object elsewhere in the stream.  Only a full serialized witness
    with a complete expected extent enters the formal forward/reverse maps.
    """

    expected = edge.get("expected_extent")
    return bool(
        edge.get("coverage") == "full"
        and edge.get("mapping_status") in {"complete", "verified"}
        and isinstance(expected, dict)
        and expected.get("status") in {"complete", "verified"}
        and _is_sha256(edge.get("witness_sha256"))
        and isinstance(edge.get("locator"), dict)
    )


def _native_lineage_runtime_chunk_mapping(
    base: dict[str, Any],
    *,
    document: NativeDocxDocumentMap,
    content: str,
    lineage: dict[str, Any],
    source_sha256: str,
    source_span: Any = None,
) -> dict[str, Any]:
    base["mapping_mode"] = "native_docx_lineage"
    # Keep a splitter-provided execution-stream interval as an integrity
    # witness for the trace.  It is never used to select a canonical object;
    # structural locators and parser value witnesses do that.  If both the
    # stored chunk and lineage carry an interval, they must agree exactly.
    runtime_span = normalize_source_span(source_span)
    lineage_span = normalize_source_span(lineage.get("source_span"))
    if runtime_span is not None and lineage_span is not None and runtime_span != lineage_span:
        base["reason"] = "native_lineage_source_span_mismatch"
        return base
    verified_span = runtime_span or lineage_span
    if verified_span is not None:
        base["source_span"] = {
            "start": verified_span[0],
            "end": verified_span[1],
        }
    if not source_sha256:
        base["reason"] = "native_source_sha256_missing"
        return base
    if not _is_sha256(source_sha256):
        base["reason"] = "native_source_sha256_malformed"
        return base
    if not document.source_sha256:
        base["reason"] = "native_canonical_source_sha256_missing"
        return base
    if document.source_sha256 != source_sha256:
        base["reason"] = "native_source_sha256_mismatch"
        return base
    if str(lineage.get("source_sha256") or "") != source_sha256:
        base["reason"] = "native_lineage_source_sha256_mismatch"
        return base
    if lineage.get("parsed_content_length") != len(content) or lineage.get(
        "parsed_content_sha256"
    ) != sha256_text(content):
        base["reason"] = "native_lineage_content_digest_mismatch"
        return base
    edges: list[dict[str, Any]] = []
    seen: set[str] = set()
    ambiguous_atoms: list[dict[str, Any]] = []
    witness_failures: list[dict[str, Any]] = []
    table_witness_failures: list[dict[str, Any]] = []
    unmatched_objects: list[dict[str, Any]] = []
    for atom in lineage.get("atoms") or []:
        if not isinstance(atom, dict):
            continue
        atom_source_sha = str(atom.get("source_sha256") or "")
        if atom_source_sha != source_sha256:
            # A missing or different atom pin is not a local text mismatch:
            # it means this lineage object cannot be trusted against the
            # caller's source.  Do not let other edges mask that tamper.
            if atom_source_sha:
                base["reason"] = "native_lineage_atom_source_sha256_mismatch"
            else:
                base["reason"] = "native_lineage_atom_source_sha256_missing"
            return base
        candidates = _native_candidates_for_atom(atom, document)
        if len(candidates) > 1:
            ambiguous_atoms.append(
                {
                    "kind": atom.get("kind"),
                    "locator": _native_locator_coordinates(atom),
                }
            )
        elif len(candidates) == 0:
            unmatched_objects.append(
                {
                    "kind": atom.get("kind"),
                    "locator": _native_locator_coordinates(atom),
                }
            )
        else:
            item = candidates[0]
            atom_for_edge = atom
            witness_matches = _native_witness_matches(
                atom, item, content=content, document=document
            )
            source_status = str(atom.get("coverage_status") or "complete")
            canonical_complete = item.representation_status == "complete"
            if not witness_matches and atom.get("kind") == "table":
                # The table envelope is a summary witness.  A vertical-merge
                # continuation can differ between python-docx's rendered grid
                # (which repeats the origin text) and the canonical physical
                # grid (which records the continuation as empty).  Retain the
                # structurally selected table edge, but explicitly downgrade
                # it; physical-cell witnesses below remain authoritative.
                table_witness_failures.append(
                    {
                        "object_id": item.object_id,
                        "kind": atom.get("kind"),
                    }
                )
                atom_for_edge = dict(atom)
                atom_for_edge["coverage_status"] = "partial"
                atom_for_edge["missing_reason"] = "table_source_value_witness_mismatch"
            elif not witness_matches and (source_status != "complete" or not canonical_complete):
                # A clipped parser atom or a canonical object explicitly
                # marked partial cannot provide a complete value witness.
                # Retain the structural edge as partial so one bad neighbour
                # (for example a vertical-merge continuation or drawing
                # placeholder) does not poison unrelated complete objects.
                atom_for_edge = dict(atom)
                atom_for_edge["coverage_status"] = "partial"
                atom_for_edge["missing_reason"] = (
                    "canonical_object_partial"
                    if not canonical_complete
                    else "runtime_source_value_witness_partial"
                )
            elif not witness_matches:
                witness_failures.append(
                    {
                        "object_id": item.object_id,
                        "kind": atom.get("kind"),
                    }
                )
            if (
                witness_matches
                or atom.get("kind") == "table"
                or source_status != "complete"
                or not canonical_complete
            ) and item.object_id not in seen:
                edges.append(
                    _native_runtime_edge(
                        item,
                        atom=atom_for_edge,
                        cell=None,
                        content_length=len(content),
                    )
                )
                seen.add(item.object_id)
        if atom.get("kind") != "table":
            continue
        for raw_cell in atom.get("cells") or []:
            if not isinstance(raw_cell, dict):
                continue
            candidates = _native_cell_candidates(
                raw_cell, table_atom=atom, document=document
            )
            if len(candidates) > 1:
                ambiguous_atoms.append(
                    {
                        "kind": "table_cell",
                        "locator": raw_cell.get("source_locator"),
                    }
                )
                continue
            if len(candidates) != 1:
                if len(candidates) == 0:
                    unmatched_objects.append(
                        {
                            "kind": "table_cell",
                            "locator": raw_cell.get("source_locator"),
                        }
                    )
                continue
            item = candidates[0]
            witness_matches = _native_witness_matches(
                raw_cell, item, content=content, document=document
            )
            cell_status = str(raw_cell.get("coverage_status") or "complete")
            canonical_complete = item.representation_status == "complete"
            if not witness_matches and cell_status == "complete" and canonical_complete:
                witness_failures.append(
                    {"object_id": item.object_id, "kind": "table_cell"}
                )
                continue
            if not witness_matches:
                raw_cell = dict(raw_cell)
                raw_cell["coverage_status"] = "partial"
                raw_cell["missing_reason"] = (
                    "canonical_object_partial"
                    if not canonical_complete
                    else "runtime_source_value_witness_partial"
                )
            if item.object_id in seen:
                continue
            edges.append(
                _native_runtime_edge(
                    item,
                    atom=atom,
                    cell=raw_cell,
                    content_length=len(content),
                )
            )
            seen.add(item.object_id)
    if ambiguous_atoms:
        base["ambiguous_objects"] = ambiguous_atoms
    if witness_failures:
        base["witness_failures"] = witness_failures
    if unmatched_objects:
        base["unmatched_objects"] = unmatched_objects
    # Keep diagnostic projections visible without exposing them as formal
    # forward edges.  The evaluator's run-level round-trip validator walks
    # ``canonical_objects``/``edges``; partial entries belong in this
    # explicitly non-proof field instead.
    formal_edges = [edge for edge in edges if _native_formal_edge(edge)]
    diagnostic_edges = [edge for edge in edges if not _native_formal_edge(edge)]
    base["canonical_objects"] = formal_edges
    base["canonical_edges"] = formal_edges
    if diagnostic_edges:
        base["diagnostic_edges"] = diagnostic_edges
        base["diagnostic_edge_count"] = len(diagnostic_edges)
    if not edges:
        base["reason"] = (
            "ambiguous_native_structural_locator"
            if ambiguous_atoms
            else "native_source_value_witness_mismatch"
            if witness_failures
            else "native_lineage_objects_not_in_canonical_catalog"
        )
        return base
    base["provenance_status"] = (
        "full"
        if not ambiguous_atoms
        and not witness_failures
        and not unmatched_objects
        and all(edge.get("coverage") == "full" for edge in edges)
        else "partial"
    )
    base["lineage_status"] = base["provenance_status"]
    if table_witness_failures:
        base["reason"] = "native_table_source_value_witness_mismatch"
        base["witness_failures"] = table_witness_failures
    elif ambiguous_atoms:
        base["reason"] = "ambiguous_native_structural_locator"
    elif witness_failures:
        base["reason"] = "native_source_value_witness_mismatch"
    elif unmatched_objects:
        base["reason"] = "native_lineage_objects_not_in_canonical_catalog"
    elif diagnostic_edges and not base.get("reason"):
        base["reason"] = "native_partial_edges_diagnostic_only"
    else:
        base["reason"] = None
    base["source_sha256"] = source_sha256
    base["lineage_sha256"] = sha256_text(
        json.dumps(lineage, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    )
    base["structure"] = {
        "metadata_status": "complete",
        "missing_fields": [],
        "section_ids": [],
        "canonical_object_count": len(formal_edges),
        "canonical_object_types": sorted(
            {str(edge.get("object_type")) for edge in formal_edges}
        ),
        "table_ids": sorted(
            {
                str(edge.get("locator", {}).get("table_id"))
                for edge in formal_edges
                if edge.get("locator", {}).get("type") == "table_cell"
            }
        ),
    }
    return base


def native_docx_runtime_chunk_mapping(
    *,
    chunk_id: str,
    document: NativeDocxDocumentMap,
    content: str,
    source_span: Any,
    lineage: Any = None,
    source_sha256: str | None = None,
    allow_historical_fallback: bool = False,
) -> dict[str, Any]:
    """Attribute one native-parser runtime chunk without using execution text.

    The trace span is retained and later required to match query-time evidence;
    it is a trace integrity check, not an unverified replacement for the DOCX
    source stream.  A table's canonical identifiers are emitted only after the
    whole table grid matches exactly and uniquely.
    """

    base: dict[str, Any] = {
        "runtime_chunk_id": chunk_id,
        "document_id": document.document_id,
        "content_sha256": sha256_text(content),
        "provenance_status": "missing",
        "canonical_objects": [],
        "canonical_edges": [],
        "structure": {
            "metadata_status": "missing",
            "missing_fields": ["canonical_object_mapping"],
            "section_ids": [],
            "canonical_object_count": 0,
        },
    }
    trusted_source_sha = str(source_sha256 or document.source_sha256 or "")
    if isinstance(lineage, dict):
        return _native_lineage_runtime_chunk_mapping(
            base,
            document=document,
            content=content,
            lineage=lineage,
            source_sha256=trusted_source_sha,
            source_span=source_span,
        )
    if not allow_historical_fallback:
        base["mapping_mode"] = "native_docx_lineage"
        base["reason"] = "native_lineage_missing"
        return base
    base["mapping_mode"] = "native_docx_grid_historical_fallback"
    span = normalize_source_span(source_span)
    if span is None:
        base["reason"] = "missing_or_malformed_source_span"
        return base
    base["source_span"] = {"start": span[0], "end": span[1]}
    runtime_tables = _runtime_json_tables(content)
    if not runtime_tables:
        base["reason"] = "native_docx_runtime_table_not_found"
        return base
    canonical_objects: list[dict[str, Any]] = []
    ambiguous = False
    for runtime_grid in runtime_tables:
        candidates = [table for table in document.tables if table.grid == runtime_grid]
        if len(candidates) != 1:
            ambiguous = ambiguous or len(candidates) > 1
            continue
        for item in candidates[0].cells:
            canonical_objects.append(
                {
                    **item,
                    "source_span": {"start": span[0], "end": span[1]},
                    "overlap_span": {"start": span[0], "end": span[1]},
                    "coverage": "full",
                    "witness_sha256": sha256_text(content),
                }
            )
    if not canonical_objects:
        base["reason"] = (
            "ambiguous_native_docx_table_grid"
            if ambiguous
            else "native_docx_table_grid_not_in_canonical_sidecar"
        )
        return base
    base["canonical_objects"] = canonical_objects
    base["provenance_status"] = "full"
    base["reason"] = None
    base["structure"] = {
        "metadata_status": "partial",
        "missing_fields": ["section_mapping", "execution_text_span"],
        "section_ids": [],
        "canonical_object_count": len(canonical_objects),
        "canonical_object_types": ["cell"],
        "table_ids": sorted(
            {str(item["locator"]["table_id"]) for item in canonical_objects}
        ),
    }
    return base


def merge_provenance_manifests(*manifests: dict[str, Any]) -> dict[str, Any]:
    """Combine source/native bridges while retaining the run-level indexes.

    The large catalog is loaded once by the evaluator.  It therefore lives at
    map scope (with a reverse-index alias), while each runtime chunk carries
    only its sparse forward edges.  Unknown future top-level contract fields
    are retained when they are mapping-shaped so a bridge cannot silently
    discard source pins or execution-stream references during composition.
    """

    documents: dict[str, Any] = {}
    runtime_chunks: dict[str, Any] = {}
    object_to_runtime_chunks: dict[str, list[dict[str, Any]]] = {}
    merged_maps: dict[str, dict[str, Any]] = {
        "object_catalog": {},
        "native_documents": {},
        "document_source_pins": {},
        "runtime_documents": {},
        "execution_streams": {},
    }
    merged_lists: dict[str, list[Any]] = {"edges": []}
    for manifest in manifests:
        for document_id, value in dict(manifest.get("documents") or {}).items():
            if document_id in documents:
                raise RuntimeError(f"duplicate provenance document: {document_id}")
            documents[document_id] = value
        for chunk_id, value in dict(manifest.get("runtime_chunks") or {}).items():
            if chunk_id in runtime_chunks:
                raise RuntimeError(f"duplicate provenance runtime chunk: {chunk_id}")
            runtime_chunks[chunk_id] = value
        for object_id, values in dict(manifest.get("object_to_runtime_chunks") or {}).items():
            if not isinstance(values, list):
                raise RuntimeError("provenance reverse index is malformed")
            object_to_runtime_chunks.setdefault(object_id, []).extend(values)
        for field in merged_maps:
            value = manifest.get(field)
            if not isinstance(value, dict):
                continue
            for key, item in value.items():
                if key in merged_maps[field] and merged_maps[field][key] != item:
                    raise RuntimeError(
                        f"duplicate provenance {field} entry: {key}"
                    )
                merged_maps[field][key] = item
        raw_edges = manifest.get("edges")
        if isinstance(raw_edges, list):
            merged_lists["edges"].extend(raw_edges)
    for values in object_to_runtime_chunks.values():
        values.sort(key=lambda item: str(item.get("runtime_chunk_id") or ""))
    result: dict[str, Any] = {
        "schema_version": MAP_SCHEMA_VERSION,
        "documents": {key: documents[key] for key in sorted(documents)},
        "runtime_chunks": {key: runtime_chunks[key] for key in sorted(runtime_chunks)},
        "object_to_runtime_chunks": {
            key: object_to_runtime_chunks[key] for key in sorted(object_to_runtime_chunks)
        },
        "reverse_index": {
            key: object_to_runtime_chunks[key]
            for key in sorted(object_to_runtime_chunks)
        },
    }
    for field, value in merged_maps.items():
        if value:
            result[field] = {key: value[key] for key in sorted(value)}
    if merged_lists["edges"]:
        result["edges"] = merged_lists["edges"]
    return result


def _read_canonical_records(document_id: str, payload: bytes) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for line_number, line in enumerate(payload.decode("utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        value = json.loads(line)
        if not isinstance(value, dict):
            raise ValueError(f"canonical provenance line {line_number} is not an object")
        if value.get("document_id") != document_id:
            raise ValueError(
                f"canonical provenance line {line_number} has wrong document_id"
            )
        records.append(value)
    if not records:
        raise ValueError("canonical provenance sidecar is empty")
    return records


def _canonicalizer_identity(record: dict[str, Any]) -> str | None:
    direct = record.get("canonicalizer")
    if isinstance(direct, str) and direct:
        return direct
    provenance = record.get("provenance")
    nested = (
        provenance.get("canonicalizer_identity")
        if isinstance(provenance, dict)
        else None
    )
    return nested if isinstance(nested, str) and nested else None


def _native_source_sha256(record: dict[str, Any]) -> str:
    direct = record.get("source_sha256")
    if isinstance(direct, str) and direct:
        return direct
    provenance = record.get("provenance")
    if isinstance(provenance, dict):
        nested = provenance.get("source_sha256")
        if isinstance(nested, str) and nested:
            return nested
    return ""


def _native_structural_locator(record: dict[str, Any]) -> dict[str, Any]:
    """Normalize direct and Canonical-contract source locator shapes."""

    direct = record.get("structural_locator")
    if isinstance(direct, dict):
        return dict(direct)
    direct = record.get("source_locator")
    if isinstance(direct, dict):
        return dict(direct)
    provenance = record.get("provenance")
    if isinstance(provenance, dict):
        spans = provenance.get("source_spans")
        if isinstance(spans, list) and spans and isinstance(spans[0], dict):
            span = spans[0]
            coordinates = span.get("coordinates")
            locator = dict(coordinates) if isinstance(coordinates, dict) else {}
            part = span.get("part")
            if isinstance(part, str) and part:
                locator["part"] = part
            return locator
    return {}


def _native_object_type(record: dict[str, Any]) -> str:
    value = record.get("object_type") or record.get("record_type") or ""
    return str(value)


def _native_status(record: dict[str, Any]) -> str:
    value = str(record.get("representation_status") or record.get("status") or "")
    return {
        "supported": "complete",
        "complete": "complete",
        "partial": "partial",
        "unsupported": "unsupported",
        "missing": "missing",
    }.get(value, value or "missing")


def _native_object_expected_extent(
    record: dict[str, Any], locator: dict[str, Any]
) -> dict[str, Any]:
    raw = record.get("expected_extent")
    if isinstance(raw, dict):
        extent = dict(raw)
    else:
        extent = {}
    attributes = record.get("attributes")
    if isinstance(attributes, dict):
        for key in (
            "row",
            "column",
            "grid_span",
            "v_merge",
            "row_span",
            "column_span",
            "physical_cell_index",
            "table_id",
            "body_ordinal",
        ):
            if key in attributes and key not in extent:
                extent[key] = attributes[key]
    for key in (
        "row",
        "column",
        "grid_span",
        "v_merge",
        "physical_cell_index",
        "table_id",
        "body_ordinal",
    ):
        if key in locator and key not in extent:
            extent[key] = locator[key]
    # The evaluator only treats an extent as a proof of a definitive miss
    # when the producer explicitly states that the extent is complete.  A
    # source object marked partial/unsupported must remain diagnostic even if
    # its structural coordinates happen to be present.
    if "status" not in extent:
        representation_status = _native_status(record)
        extent["status"] = (
            "complete"
            if representation_status == "complete"
            else "partial"
            if representation_status == "partial"
            else "missing"
        )
    # A body ordinal alone is not an evaluator-valid extent: it cannot be
    # tied back to the object if a document contains duplicate/parallel
    # structures.  Include both the stable object id and its typed locator in
    # every extent.  Keep the raw structural coordinates on the object as
    # ``source_locator``; this nested typed copy is the proof-facing shape.
    if isinstance(record.get("object_id"), str) and record["object_id"]:
        extent.setdefault("object_id", record["object_id"])
    extent.setdefault("locator", _native_typed_locator(record, locator))
    return extent


def _native_typed_locator(record: dict[str, Any], locator: dict[str, Any]) -> dict[str, Any]:
    """Build the platform EvidenceLocator shape for an object edge."""

    object_id = str(record.get("object_id") or "")
    object_type = _native_object_type(record)
    table_id = record.get("table_id") or locator.get("table_id")
    row = record.get("row")
    if row is None:
        row = locator.get("row")
    column = record.get("column")
    if column is None:
        column = locator.get("column")
    if (
        object_type in {"cell", "logical_cell", "table_cell"}
        and isinstance(table_id, str)
        and table_id
        and isinstance(row, (int, str))
        and not isinstance(row, bool)
        and isinstance(column, (int, str))
        and not isinstance(column, bool)
    ):
        return {
            "type": "table_cell",
            "table_id": table_id,
            "row": row,
            "column": column,
        }
    return {"type": "object", "object_type": object_type, "object_id": object_id}


def _normalize_table_cell(value: Any) -> str:
    return " ".join(unicodedata.normalize("NFKC", str(value or "")).split())


_RUNTIME_JSON_TABLE = re.compile(
    r"<table\b(?P<attributes>[^>]*)>(?P<body>\s*\[\[.*?\]\]\s*)</table>",
    flags=re.IGNORECASE | re.DOTALL,
)


def _runtime_json_tables(content: str) -> list[tuple[tuple[str, ...], ...]]:
    tables: list[tuple[tuple[str, ...], ...]] = []
    for match in _RUNTIME_JSON_TABLE.finditer(content):
        attributes = match.group("attributes")
        if not re.search(r"\bformat\s*=\s*['\"]json['\"]", attributes, re.I):
            continue
        try:
            raw_grid = json.loads(match.group("body"))
        except json.JSONDecodeError:
            continue
        if (
            not isinstance(raw_grid, list)
            or not raw_grid
            or any(not isinstance(row, list) or not row for row in raw_grid)
        ):
            continue
        width = len(raw_grid[0])
        if width < 1 or any(len(row) != width for row in raw_grid):
            continue
        tables.append(
            tuple(tuple(_normalize_table_cell(value) for value in row) for row in raw_grid)
        )
    return tables


def write_provenance_manifest(path: Path, manifest: dict[str, Any]) -> str:
    payload = json.dumps(
        manifest,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    path.write_bytes(payload)
    return sha256_bytes(payload)


def normalize_source_span(value: Any) -> tuple[int, int] | None:
    if not isinstance(value, dict):
        return None
    start = value.get("start")
    end = value.get("end")
    if (
        not isinstance(start, int)
        or isinstance(start, bool)
        or not isinstance(end, int)
        or isinstance(end, bool)
        or start < 0
        or end <= start
    ):
        return None
    return start, end


def _build_canonical_structure(
    records: list[dict[str, Any]],
) -> tuple[dict[str, dict[str, Any]], dict[str, dict[str, Any]]]:
    """Build a document graph exclusively from canonicalizer-v1 fields.

    This is deliberately independent of execution text.  The canonicalizer
    owns heading levels, body order, section membership, and table topology;
    this bridge only preserves and relates those fields.
    """

    by_id = {
        str(record.get("object_id")): record
        for record in records
        if isinstance(record.get("object_id"), str) and record["object_id"]
    }
    section_records = [
        record for record in records if record.get("object_type") == "section"
    ]
    root_sections = [
        record
        for record in section_records
        if not isinstance(_heading_level(record), int)
    ]
    root_id = str(root_sections[0].get("object_id")) if root_sections else None
    heading_sections = sorted(
        (
            record
            for record in section_records
            if _body_ordinal(record) is not None
            and _heading_level(record) is not None
        ),
        key=lambda record: (_body_ordinal(record) or -1, str(record.get("object_id"))),
    )

    section_specs: dict[str, dict[str, Any]] = {}
    if root_id is not None:
        section_specs[root_id] = {
            "section_id": root_id,
            "heading_path": None,
            "parent_section_id": None,
            "heading_level": None,
            "document_order": None,
            "section_role": "document_body",
            "metadata_status": "partial",
            "missing_fields": ["heading_level", "document_order"],
        }
    stack: dict[int, str] = {}
    for record in heading_sections:
        section_id = str(record.get("object_id"))
        level = _heading_level(record)
        order = _body_ordinal(record)
        title = str(record.get("canonical_value") or "").strip()
        if not isinstance(level, int) or order is None:
            continue
        parent = next(
            (stack[key] for key in sorted(stack, reverse=True) if key < level),
            root_id,
        )
        parent_path = (
            str(section_specs[parent].get("heading_path") or "")
            if parent in section_specs
            else ""
        )
        path = " → ".join(value for value in (parent_path, title) if value)
        missing = [] if title else ["heading_title"]
        section_specs[section_id] = {
            "section_id": section_id,
            "heading_path": path or None,
            "parent_section_id": parent,
            "heading_level": level,
            "document_order": order,
            "section_role": "section",
            "metadata_status": "complete" if not missing else "partial",
            "missing_fields": missing,
        }
        stack[level] = section_id
        for nested in tuple(stack):
            if nested > level:
                del stack[nested]

    section_by_body = {
        _body_ordinal(record): str(record.get("object_id"))
        for record in heading_sections
        if _body_ordinal(record) is not None
    }
    block_sections: dict[str, str | None] = {}
    table_sections: dict[str, str | None] = {}
    row_by_table_position: dict[tuple[str, int], str] = {}
    for record in records:
        object_id = str(record.get("object_id") or "")
        locator = _structural_locator(record)
        object_type = str(record.get("object_type") or "")
        if object_type == "block":
            section_id = (
                section_by_body.get(_body_ordinal(record))
                if record.get("block_kind") == "heading"
                else _text_or_none(locator.get("section_id"))
            )
            block_sections[object_id] = section_id
        elif object_type == "table":
            table_sections[object_id] = _text_or_none(locator.get("section_id"))
        elif object_type == "row":
            table_id = _text_or_none(record.get("table_id")) or _text_or_none(
                locator.get("table_id")
            )
            row = locator.get("row")
            if table_id is not None and isinstance(row, int):
                row_by_table_position[(table_id, row)] = object_id

    structures: dict[str, dict[str, Any]] = {}
    role_by_block_kind = {
        "heading": "heading",
        "paragraph": "paragraph",
        "caption": "caption",
        "list_item": "list_item",
    }
    for object_id, record in by_id.items():
        locator = _structural_locator(record)
        object_type = str(record.get("object_type") or "")
        document_order = _body_ordinal(record)
        section_id: str | None
        parent_object_id: str | None
        table_id = _text_or_none(record.get("table_id")) or _text_or_none(
            locator.get("table_id")
        )
        row_id = _text_or_none(record.get("row_id"))
        row_number = locator.get("row")
        column_number = locator.get("column")
        if object_type == "section":
            section_id = object_id
            parent_object_id = _text_or_none(
                section_specs.get(object_id, {}).get("parent_section_id")
            )
        elif object_type == "block":
            section_id = block_sections.get(object_id)
            if record.get("block_kind") == "heading" and section_id in section_specs:
                parent_object_id = _text_or_none(
                    section_specs[section_id].get("parent_section_id")
                )
            else:
                parent_object_id = section_id
        elif object_type == "text_span":
            parent_object_id = _text_or_none(record.get("block_id")) or _text_or_none(
                locator.get("block_id")
            )
            section_id = block_sections.get(parent_object_id or "")
        elif object_type == "table":
            section_id = table_sections.get(object_id)
            parent_object_id = section_id
            table_id = object_id
        elif object_type == "row":
            section_id = table_sections.get(table_id or "")
            parent_object_id = table_id
            row_id = object_id
        elif object_type == "cell":
            section_id = table_sections.get(table_id or "")
            if table_id is not None and isinstance(row_number, int):
                parent_object_id = row_by_table_position.get((table_id, row_number))
            else:
                parent_object_id = None
        else:
            section_id = _text_or_none(locator.get("section_id"))
            parent_object_id = section_id

        section = section_specs.get(section_id or "")
        missing: list[str] = []
        if document_order is None and object_type not in {"document", "section"}:
            missing.append("document_order")
        if section is None:
            missing.append("section_mapping")
        elif section.get("metadata_status") != "complete":
            missing.append("complete_section_metadata")
        role = role_by_block_kind.get(
            str(record.get("block_kind") or ""),
            {
                "section": "section",
                "table": "table",
                "row": "table_row",
                "cell": "table_cell",
            }.get(object_type, object_type or "unknown"),
        )
        structures[object_id] = {
            "metadata_status": "complete" if not missing else "partial",
            "missing_fields": missing,
            "document_order": document_order,
            "section_id": section_id,
            "heading_path": section.get("heading_path") if section else None,
            "parent_section_id": section.get("parent_section_id") if section else None,
            "section_role": section.get("section_role") if section else None,
            "object_role": role,
            "parent_object_id": parent_object_id,
            "table_id": table_id,
            "row_id": row_id,
            "table_row_index": row_number if isinstance(row_number, int) else None,
            "table_column_index": (
                column_number if isinstance(column_number, int) else None
            ),
        }

    sibling_groups: dict[str, list[str]] = {}
    for object_id, structure in structures.items():
        parent = _text_or_none(structure.get("parent_object_id"))
        if parent is not None and parent != object_id:
            sibling_groups.setdefault(parent, []).append(object_id)
    role_order = {
        "section": 0,
        "heading": 1,
        "paragraph": 2,
        "list_item": 3,
        "table": 4,
        "caption": 5,
        "table_row": 6,
        "table_cell": 7,
    }
    for siblings in sibling_groups.values():
        siblings.sort(
            key=lambda object_id: (
                structures[object_id].get("document_order")
                if isinstance(structures[object_id].get("document_order"), int)
                else 10**12,
                role_order.get(str(structures[object_id].get("object_role")), 99),
                object_id,
            )
        )
        for index, object_id in enumerate(siblings):
            structures[object_id].update(
                {
                    "sibling_index": index,
                    "sibling_count": len(siblings),
                    "preceding_sibling_object_id": (
                        siblings[index - 1] if index else None
                    ),
                    "following_sibling_object_id": (
                        siblings[index + 1]
                        if index + 1 < len(siblings)
                        else None
                    ),
                }
            )
    return structures, section_specs


def _materialize_sections(
    section_specs: dict[str, dict[str, Any]],
    objects: list[CanonicalObjectSpan],
    source: str,
) -> list[dict[str, Any]]:
    """Attach exact execution spans to canonical section hierarchy entries."""

    source_length = len(source)
    heading_spans = {
        item.object_id: (
            source.rfind("\n", 0, item.start) + 1,
            item.end,
        )
        for item in objects
        if item.object_type == "section" and item.object_id in section_specs
    }
    ordered = sorted(
        heading_spans,
        key=lambda object_id: (heading_spans[object_id][0], object_id),
    )
    first_heading_start = heading_spans[ordered[0]][0] if ordered else source_length
    sections: list[dict[str, Any]] = []
    for section_id, spec in sorted(
        section_specs.items(),
        key=lambda item: (
            item[1].get("document_order")
            if isinstance(item[1].get("document_order"), int)
            else -1,
            item[0],
        ),
    ):
        value = dict(spec)
        span = heading_spans.get(section_id)
        if span is None:
            if value.get("section_role") == "document_body":
                value["active_source_span"] = {"start": 0, "end": first_heading_start}
            else:
                value["metadata_status"] = "partial"
                value["missing_fields"] = sorted(
                    set(value.get("missing_fields") or []) | {"source_span"}
                )
            sections.append(value)
            continue
        position = ordered.index(section_id)
        next_start = (
            heading_spans[ordered[position + 1]][0]
            if position + 1 < len(ordered)
            else source_length
        )
        value["source_span"] = {"start": span[0], "end": span[1]}
        value["active_source_span"] = {"start": span[0], "end": next_start}
        sections.append(value)
    return sections


def _structural_locator(record: dict[str, Any]) -> dict[str, Any]:
    value = record.get("structural_locator")
    return value if isinstance(value, dict) else {}


def _heading_level(record: dict[str, Any]) -> int | None:
    value = _structural_locator(record).get("heading_level")
    return value if isinstance(value, int) and not isinstance(value, bool) else None


def _text_or_none(value: Any) -> str | None:
    return str(value) if isinstance(value, str) and value else None


def _align_canonicalizer_v1(
    source: str,
    records: list[dict[str, Any]],
    structures: dict[str, dict[str, Any]],
) -> tuple[list[CanonicalObjectSpan], list[dict[str, str]]]:
    aligned: dict[str, CanonicalObjectSpan] = {}
    diagnostics: list[dict[str, str]] = []
    lines = _source_lines(source)
    lines_by_text: dict[str, list[tuple[int, int]]] = {}
    for text, start, end in lines:
        lines_by_text.setdefault(text, []).append((start, end))
    records_by_type: dict[str, list[dict[str, Any]]] = {}
    for record in records:
        records_by_type.setdefault(str(record.get("object_type") or ""), []).append(
            record
        )

    sections_by_body = {
        _body_ordinal(record): record
        for record in records_by_type.get("section", [])
        if _body_ordinal(record) is not None
    }
    blocks_by_body: dict[int, dict[str, Any]] = {}
    cursor = 0
    for record in sorted(
        records_by_type.get("block", []),
        key=lambda item: (_body_ordinal(item) or -1, str(item.get("object_id"))),
    ):
        if record.get("status") == "unsupported":
            _diagnose(diagnostics, record, "unsupported_object")
            continue
        body_ordinal = _body_ordinal(record)
        if body_ordinal is not None:
            blocks_by_body[body_ordinal] = record
        value = str(record.get("canonical_value") or "")
        expected = _rendered_block_line(record, sections_by_body.get(body_ordinal))
        matches = lines_by_text.get(expected, [])
        match = next((item for item in matches if item[0] >= cursor), None)
        if match is None or not value:
            _diagnose(diagnostics, record, "execution_line_not_found")
            continue
        line_start, line_end = match
        relative = expected.find(value)
        if relative < 0:
            _diagnose(diagnostics, record, "canonical_value_not_in_execution_line")
            continue
        _add_span(
            aligned,
            record,
            source,
            line_start + relative,
            line_start + relative + len(value),
            "canonicalizer_v1_block_line",
            structures,
        )
        cursor = line_end

    for record in records_by_type.get("text_span", []):
        block_id = str(record.get("block_id") or "")
        parent = aligned.get(block_id)
        if parent is None:
            _diagnose(diagnostics, record, "parent_block_not_aligned")
            continue
        _copy_span(
            aligned,
            record,
            source,
            parent,
            "canonicalizer_v1_text_span",
            structures,
        )
    for record in records_by_type.get("section", []):
        body_ordinal = _body_ordinal(record)
        block = blocks_by_body.get(body_ordinal) if body_ordinal is not None else None
        parent = aligned.get(str(block.get("object_id"))) if block else None
        if parent is None:
            _diagnose(diagnostics, record, "section_heading_not_aligned")
            continue
        _copy_span(
            aligned,
            record,
            source,
            parent,
            "canonicalizer_v1_section_heading",
            structures,
        )

    table_records = records_by_type.get("table", [])
    rows = records_by_type.get("row", [])
    cells = records_by_type.get("cell", [])
    for table in table_records:
        _align_table(source, table, rows, cells, aligned, diagnostics, structures)

    for object_type, prefix in (("figure", "Figure: "), ("equation", "Equation: ")):
        for record in records_by_type.get(object_type, []):
            if record.get("status") == "unsupported":
                _diagnose(diagnostics, record, "unsupported_object")
                continue
            value = str(record.get("canonical_value") or "")
            matches = lines_by_text.get(prefix + value, [])
            if len(matches) != 1 or not value:
                _diagnose(diagnostics, record, "rich_object_line_not_unique")
                continue
            start = matches[0][0] + len(prefix)
            _add_span(
                aligned,
                record,
                source,
                start,
                start + len(value),
                "canonicalizer_v1_rich_object_line",
                structures,
            )

    for object_type in ("reference", "note"):
        for record in records_by_type.get(object_type, []):
            if record.get("status") == "unsupported":
                _diagnose(diagnostics, record, "unsupported_object")
                continue
            body_ordinal = _body_ordinal(record)
            block = (
                blocks_by_body.get(body_ordinal) if body_ordinal is not None else None
            )
            parent = aligned.get(str(block.get("object_id"))) if block else None
            value = str(record.get("canonical_value") or "")
            if parent is None or not value:
                _diagnose(diagnostics, record, "body_anchor_not_aligned")
                continue
            parent_text = source[parent.start : parent.end]
            relative = parent_text.find(value)
            if relative < 0 or parent_text.find(value, relative + 1) >= 0:
                _diagnose(diagnostics, record, "anchored_value_not_unique")
                continue
            _add_span(
                aligned,
                record,
                source,
                parent.start + relative,
                parent.start + relative + len(value),
                "canonicalizer_v1_body_anchor",
                structures,
            )

    return (
        sorted(
            aligned.values(), key=lambda item: (item.start, item.end, item.object_id)
        ),
        sorted(diagnostics, key=lambda item: (item["object_id"], item["reason"])),
    )


def _align_table(
    source: str,
    table: dict[str, Any],
    rows: list[dict[str, Any]],
    cells: list[dict[str, Any]],
    aligned: dict[str, CanonicalObjectSpan],
    diagnostics: list[dict[str, str]],
    structures: dict[str, dict[str, Any]],
) -> None:
    table_id = str(table.get("object_id") or "")
    width = table.get("column_count")
    row_count = table.get("row_count")
    if not isinstance(width, int) or width < 1 or not isinstance(row_count, int):
        _diagnose(diagnostics, table, "invalid_table_shape")
        return
    table_cells = [record for record in cells if record.get("table_id") == table_id]
    values = [["" for _ in range(width)] for _ in range(row_count)]
    cell_by_position: dict[tuple[int, int], dict[str, Any]] = {}
    for cell in table_cells:
        row = cell.get("row")
        column = cell.get("column")
        if not isinstance(row, int) or not isinstance(column, int):
            continue
        if 1 <= row <= row_count and 1 <= column <= width:
            values[row - 1][column - 1] = str(cell.get("canonical_value") or "")
            cell_by_position[(row, column)] = cell
    rendered_rows = [_render_table_row(row) for row in values]
    if not rendered_rows:
        _diagnose(diagnostics, table, "empty_table")
        return
    separator = "| " + " | ".join("---" for _ in range(width)) + " |"
    rendered_lines = [rendered_rows[0], separator, *rendered_rows[1:]]
    rendered = "\n".join(rendered_lines)
    first = source.find(rendered)
    if first < 0 or source.find(rendered, first + 1) >= 0:
        _diagnose(diagnostics, table, "table_rendering_not_unique")
        return
    _add_span(
        aligned,
        table,
        source,
        first,
        first + len(rendered),
        "canonicalizer_v1_table_rendering",
        structures,
    )
    rows_by_number = {
        record.get("row"): record
        for record in rows
        if record.get("table_id") == table_id
    }
    line_offsets: list[int] = []
    offset = 0
    for line in rendered_lines:
        line_offsets.append(offset)
        offset += len(line) + 1
    for row_number, rendered_row in enumerate(rendered_rows, start=1):
        line_index = 0 if row_number == 1 else row_number
        row_start = first + line_offsets[line_index]
        row_record = rows_by_number.get(row_number)
        if row_record is not None:
            _add_span(
                aligned,
                row_record,
                source,
                row_start,
                row_start + len(rendered_row),
                "canonicalizer_v1_table_row",
                structures,
            )
        value_offset = 2
        for column, value in enumerate(values[row_number - 1], start=1):
            rendered_value = value.replace("|", "\\|")
            cell = cell_by_position.get((row_number, column))
            if cell is not None and rendered_value:
                _add_span(
                    aligned,
                    cell,
                    source,
                    row_start + value_offset,
                    row_start + value_offset + len(rendered_value),
                    "canonicalizer_v1_table_cell",
                    structures,
                )
            value_offset += len(rendered_value)
            if column < width:
                value_offset += 3


def _rendered_block_line(block: dict[str, Any], section: dict[str, Any] | None) -> str:
    value = str(block.get("canonical_value") or "")
    kind = block.get("block_kind")
    if kind == "heading" and section is not None:
        locator = section.get("structural_locator")
        level = locator.get("heading_level") if isinstance(locator, dict) else None
        if isinstance(level, int) and 1 <= level <= 9:
            return "#" * level + " " + value
    if kind == "list_item":
        return "- " + value
    return value


def _render_table_row(values: list[str]) -> str:
    return "| " + " | ".join(value.replace("|", "\\|") for value in values) + " |"


def _source_lines(source: str) -> list[tuple[str, int, int]]:
    values: list[tuple[str, int, int]] = []
    cursor = 0
    for line in source.splitlines(keepends=True):
        text = line.rstrip("\r\n")
        values.append((text, cursor, cursor + len(text)))
        cursor += len(line)
    if source and not source.endswith(("\n", "\r")):
        return values
    return values


def _body_ordinal(record: dict[str, Any]) -> int | None:
    locator = record.get("structural_locator")
    value = locator.get("body_ordinal") if isinstance(locator, dict) else None
    return value if isinstance(value, int) and not isinstance(value, bool) else None


def _locator(record: dict[str, Any]) -> dict[str, Any]:
    if record.get("object_type") == "cell":
        return {
            "type": "table_cell",
            "table_id": str(record.get("table_id") or ""),
            "row": record.get("row"),
            "column": record.get("column"),
        }
    return {
        "type": "object",
        "object_type": str(record.get("object_type") or ""),
        "object_id": str(record.get("object_id") or ""),
    }


def _add_span(
    aligned: dict[str, CanonicalObjectSpan],
    record: dict[str, Any],
    source: str,
    start: int,
    end: int,
    method: str,
    structures: dict[str, dict[str, Any]],
) -> None:
    object_id = str(record.get("object_id") or "")
    if not object_id or start < 0 or end <= start or end > len(source):
        return
    aligned[object_id] = CanonicalObjectSpan(
        object_id=object_id,
        object_type=str(record.get("object_type") or ""),
        status=str(record.get("status") or ""),
        start=start,
        end=end,
        locator=_locator(record),
        witness_sha256=sha256_text(source[start:end]),
        alignment_method=method,
        structure=dict(
            structures.get(
                object_id,
                {
                    "metadata_status": "missing",
                    "missing_fields": ["canonical_structure"],
                },
            )
        ),
    )


def _copy_span(
    aligned: dict[str, CanonicalObjectSpan],
    record: dict[str, Any],
    source: str,
    parent: CanonicalObjectSpan,
    method: str,
    structures: dict[str, dict[str, Any]],
) -> None:
    _add_span(
        aligned,
        record,
        source,
        parent.start,
        parent.end,
        method,
        structures,
    )


def _diagnose(
    diagnostics: list[dict[str, str]], record: dict[str, Any], reason: str
) -> None:
    diagnostics.append(
        {"object_id": str(record.get("object_id") or ""), "reason": reason}
    )
